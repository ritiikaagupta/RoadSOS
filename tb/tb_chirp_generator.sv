`timescale 1ns / 1ps

// ============================================================
// SAFE-Link LoRa Chirp Generator Testbench
// Step 10
// ============================================================

module tb_chirp_generator;

    // ========================================================
    // Clock
    // ========================================================

    reg clk;

    initial begin
        clk = 1'b0;
    end

    always #5 clk = ~clk;


    // ========================================================
    // Inputs
    // ========================================================

    reg reset;
    reg enable;

    reg [31:0] phase_increment;


    // ========================================================
    // Outputs
    // ========================================================

    wire signed [15:0] i_out;
    wire signed [15:0] q_out;

    wire valid;


    // ========================================================
    // Device Under Test
    // ========================================================

    chirp_generator dut (

        .clk(clk),

        .reset(reset),

        .enable(enable),

        .phase_increment(phase_increment),

        .i_out(i_out),

        .q_out(q_out),

        .valid(valid)

    );


    // ========================================================
    // Test
    // ========================================================

    initial begin

        // ----------------------------------------------------
        // Initial conditions
        // ----------------------------------------------------

        reset = 1'b1;
        enable = 1'b0;

        phase_increment = 32'd100000000;


        // ----------------------------------------------------
        // Reset
        // ----------------------------------------------------

        #20;

        reset = 1'b0;


        // ----------------------------------------------------
        // Enable generator
        // ----------------------------------------------------

        enable = 1'b1;


        // ----------------------------------------------------
        // Run
        // ----------------------------------------------------

        #200;


        // ----------------------------------------------------
        // Disable
        // ----------------------------------------------------

        enable = 1'b0;

        #20;


        // ----------------------------------------------------
        // Finish
        // ----------------------------------------------------

        $display("------------------------------------------");
        $display("SAFE-Link Chirp Generator Test Complete");
        $display("------------------------------------------");

        $finish;

    end


    // ========================================================
    // Monitor
    // ========================================================

    always @(posedge clk) begin

        if (valid == 1'b1) begin

            $display(
                "Time=%0t ns | I=%0d | Q=%0d",
                $time,
                i_out,
                q_out
            );

        end

    end

endmodule
